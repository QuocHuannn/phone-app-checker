#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md from package-lock.json (production dependency graph, platform independent).
// Usage: npm run licenses           rewrite THIRD_PARTY_LICENSES.md
//        npm run licenses -- --check   exit 1 when the committed file is out of date (used in CI)
//
// Packages whose lock entry carries no SPDX licence must be listed in LICENSE_OVERRIDES after a human read
// their licence file; an unlisted one fails the run, so a new unknown licence cannot slip in unnoticed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'THIRD_PARTY_LICENSES.md');

/** Licence of lock entries that declare none (verified against each package's own licence file / manifest). */
const LICENSE_OVERRIDES = {
  '@evex/linejs': ['MIT', 'licence declared in the JSR manifest (deno.json)'],
  '@jsr/evex__linejs-types': ['MIT', 'licence declared in the JSR manifest (deno.json)'],
  '@jsr/evex__loose-types': ['MIT', 'LICENSE file'],
  'node-bignumber': ['MIT-style (Tom Wu), permissive', 'LICENSE file: free use, copy, modify, distribute; notice must be retained'],
  'qrcode-terminal': ['Apache-2.0', 'package.json declares "Apache 2.0"'],
};

const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const rows = new Map();
const problems = [];
for (const [path, entry] of Object.entries(lock.packages ?? {})) {
  if (path === '' || entry.dev) continue;
  const name = path.replace(/^.*node_modules\//, '');
  const override = LICENSE_OVERRIDES[name];
  const license = entry.license ?? override?.[0];
  if (license === undefined) {
    problems.push(`${name}@${entry.version}: no licence in package-lock.json and no entry in LICENSE_OVERRIDES`);
    continue;
  }
  if (/\bAGPL\b/i.test(license)) problems.push(`${name}@${entry.version}: AGPL licence (${license}) needs a decision`);
  rows.set(`${name}@${entry.version}`, { name, version: entry.version, license, optional: entry.optional === true });
}
if (problems.length > 0) {
  process.stderr.write(`${problems.join('\n')}\n`);
  process.exit(1);
}

const list = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const copyleft = list.filter((row) => /\b(L?GPL|MPL|EPL|CDDL)\b/i.test(row.license));
const counts = new Map();
for (const row of list) counts.set(row.license, (counts.get(row.license) ?? 0) + 1);
const direct = Object.keys(pkg.dependencies ?? {});

const escape = (text) => text.replaceAll('|', '\\|');
const lines = [];
lines.push('# Third-party licences', '');
lines.push(
  'phone-app-checker is licensed under the GNU General Public License, version 3 or (at your option) any later version (see [LICENSE](LICENSE)).',
  'It depends on the third-party software listed below. This file is generated by `npm run licenses` from `package-lock.json`;',
  'do not edit it by hand. Every package keeps its own licence text and copyright notice in its folder under `node_modules/`',
  '(shipped inside the macOS release archive as `app/node_modules/<package>/`), and the bundled Node.js runtime ships its licence as `runtime/LICENSE`.',
  '',
);
lines.push('## Why the project is GPL-3.0-or-later', '');
lines.push(
  '`baileys` (MIT) depends on `libsignal` (GPL-3.0, [WhiskeySockets/libsignal-node](https://github.com/WhiskeySockets/libsignal-node)), which is loaded at runtime.',
  'The macOS release archive bundles both, so the project as a whole is distributed under GPL-3.0-or-later. The other licences below',
  '(MIT, ISC, BSD, Apache-2.0, 0BSD, BlueOak, Unlicense, WTFPL, Zlib, LGPL-3.0-or-later) are compatible with GPL-3.0.',
  'Complete corresponding source: this repository at the release tag, plus the unmodified npm packages pinned in `package-lock.json`.',
  '',
);
if (copyleft.length > 0) {
  lines.push('## Copyleft components', '');
  lines.push('| Package | Version | Licence | Notes |', '| --- | --- | --- | --- |');
  const groups = new Map();
  for (const row of copyleft) {
    const group = row.name.startsWith('@img/sharp-libvips-') ? '@img/sharp-libvips-<platform>' : row.name.startsWith('@img/sharp-') ? '@img/sharp-<platform>' : row.name;
    const key = `${group}\u0000${row.version}\u0000${row.license}`;
    const entry = groups.get(key) ?? { group, version: row.version, license: row.license, count: 0 };
    entry.count += 1;
    groups.set(key, entry);
  }
  for (const row of groups.values()) {
    let note = '';
    if (row.group === 'libsignal') note = 'Loaded by Baileys; reason for the project licence (above).';
    else if (row.group === '@img/sharp-libvips-<platform>') note = `Prebuilt libvips shared library for \`sharp\` (${row.count} platform variants in the lock file, only the one for your OS/CPU is installed), used unmodified as a dynamic library and replaceable by the user. Source: <https://github.com/lovell/sharp-libvips> and <https://github.com/libvips/libvips>.`;
    else if (row.group === '@img/sharp-<platform>') note = `Prebuilt \`sharp\` addon bundling LGPL-3.0-or-later libvips (${row.count} optional platform variants, not installed on macOS arm64).`;
    lines.push(`| \`${row.group}\` | ${row.version} | ${escape(row.license)} | ${note} |`);
  }
  lines.push('');
}
lines.push('## Direct dependencies', '');
lines.push('| Package | Version | Licence |', '| --- | --- | --- |');
for (const name of direct) {
  const row = list.find((r) => r.name === name);
  if (row === undefined) {
    process.stderr.write(`direct dependency ${name} not found in package-lock.json\n`);
    process.exit(1);
  }
  lines.push(`| \`${name}\` | ${row.version} | ${escape(row.license)} |`);
}
lines.push('');
lines.push('## Bundled Node.js runtime (macOS archive only)', '');
lines.push(
  'The macOS archive carries the official, unmodified Node.js binary (version and SHA-256 pinned in `scripts/build-release.sh`, signature checked at build time).',
  'Node.js is released under the MIT licence and bundles components under other permissive licences; the full licence text is `runtime/LICENSE` inside the archive',
  'and at <https://github.com/nodejs/node/blob/main/LICENSE>.',
  '',
);
lines.push('## Licence summary of the production dependency graph', '');
lines.push(
  `${list.length} packages in \`package-lock.json\` outside \`devDependencies\` (including optional platform variants that are not installed on every OS).`,
  '',
  '| Licence | Packages |',
  '| --- | --- |',
);
for (const [license, count] of [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
  lines.push(`| ${escape(license)} | ${count} |`);
}
lines.push('');
lines.push('## All production packages', '');
lines.push('| Package | Version | Licence |', '| --- | --- | --- |');
for (const row of list) {
  const override = LICENSE_OVERRIDES[row.name];
  const suffix = override !== undefined && !lock.packages[`node_modules/${row.name}`]?.license ? ' (verified manually)' : '';
  lines.push(`| \`${row.name}\` | ${row.version} | ${escape(row.license)}${suffix} |`);
}
lines.push('');
const output = `${lines.join('\n')}`;

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(target, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== output) {
    process.stderr.write('THIRD_PARTY_LICENSES.md is out of date: run `npm run licenses` and commit the result.\n');
    process.exit(1);
  }
  process.stdout.write('THIRD_PARTY_LICENSES.md is up to date.\n');
} else {
  writeFileSync(target, output);
  process.stdout.write(`Wrote ${target} (${list.length} packages).\n`);
}
